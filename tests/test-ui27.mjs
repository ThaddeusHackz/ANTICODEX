import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const ROOT=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const read=(f)=>fs.readFileSync(path.join(ROOT,f),'utf8');
let p=0,f=0; const ok=(n,c,x)=>{ if(c){p++;console.log('  + '+n);} else {f++;console.log('  FAIL '+n+' '+(x||''));} };
console.log('--- v2.7: retry, surprise, design, CI structure ---');
const chat=read('web/src/pages/Chat.jsx');
ok('regenerate resends the preceding user turn', /messages\.slice\(0, i\)\.reverse\(\)\.find/.test(chat));
ok('error bubbles carry a Retry button', /Retry<\/button>/.test(chat));
const mp=read('web/src/ModelPicker.jsx');
ok('model picker has Surprise me', /Surprise me/.test(mp) && /const surprise = /.test(mp));
ok('surprise prefers configured + fast providers', /FAST/.test(mp) && /configured \? 4/.test(mp));
const css=read('web/src/styles.css');
ok('design layer present', /v2\.7 design layer/.test(css));
ok('centered conversation column', /\.messages \{ max-width: 48rem/.test(css));
ok('editorial serif hero', /Georgia, "Times New Roman", serif/.test(css));
const y=read('.github/workflows/release.yml');
const matrix=(y.match(/suite: \[([^\]]+)\]/)||[])[1].split(',').map(s=>s.trim()).filter(Boolean);
const arms=[...y.matchAll(/^\s*([\w-]+)\) f=(tests\/[\w.-]+\.mjs) ;;/gm)].map(m=>({suite:m[1],file:m[2]}));
const armSuites=arms.map(a=>a.suite);
ok('every matrix suite has a case arm', matrix.every(s=>armSuites.includes(s)), matrix.filter(s=>!armSuites.includes(s)).join(','));
ok('every case arm is in the matrix', armSuites.every(s=>matrix.includes(s)), armSuites.filter(s=>!matrix.includes(s)).join(','));
ok('every case arm points at a real test file', arms.every(a=>fs.existsSync(path.join(ROOT,a.file))), arms.filter(a=>!fs.existsSync(path.join(ROOT,a.file))).map(a=>a.file).join(','));
const npm=read('package.json');
ok('every matrix suite runs in npm test', matrix.every(s=>npm.includes(s==='web-static'?'test-web.mjs':'test-'+s+'.mjs')), matrix.join(','));
console.log(p+' passed, '+f+' failed'); process.exit(f?1:0);
