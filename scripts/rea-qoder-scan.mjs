#!/usr/bin/env node
// Run REA over the QoderAI repositories and write docs/QODER-REA-EVIDENCE.md.
//
// REA analyses *artifacts*, not markdown: a repository with eight release-note
// stubs has nothing for it to inventory. So this clones each repository, asks
// REA's JavaScript/Electron analyser for an evidence record, and reports the
// coverage it got — including "0 of 1" when there is nothing to analyse, which
// is the honest answer for a docs-only repository.
//
// Requires a running ANTICODEX bridge with REA registered (`/rea` → register).
//
//   node scripts/rea-qoder-scan.mjs                     # every repository
//   node scripts/rea-qoder-scan.mjs better-harness ...  # just these
//
// Output: docs/QODER-REA-EVIDENCE.md (and the raw JSON under .rea-scan/).

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFile } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { QODER_REPOS } from '../lib/qoder-repos.js';

const run = promisify(execFile);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BASE = process.env.ANTICODEX_BRIDGE || 'http://127.0.0.1:8787/api/bridge';
const OUT_DIR = path.join(root, '.rea-scan');
const DOC = path.join(root, 'docs', 'QODER-REA-EVIDENCE.md');
const CLONES = path.join(os.tmpdir(), 'anticodex-qoder-clones');

// Repositories with code worth analysing. Everything else is markdown-only or
// empty, and cloning it would only produce "0 files" rows.
const ANALYSABLE = new Set(['better-harness', 'qoder-action', 'qoder-acp-demos', 'forward-quickstart',
  'qoder-cloud-agents-sdk-ts', 'Qoderian', 'agentic-coding-durability-evalset']);

const only = process.argv.slice(2);
const targets = QODER_REPOS.filter((r) => (only.length ? only.includes(r.name) : ANALYSABLE.has(r.name)));

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.mkdirSync(CLONES, { recursive: true });

async function call(payload, timeoutMs = 900000) {
  const res = await fetch(BASE, {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload), signal: AbortSignal.timeout(timeoutMs)
  });
  return res.json();
}

const rows = [];
for (const repo of targets) {
  const dir = path.join(CLONES, repo.name);
  const raw = path.join(OUT_DIR, `${repo.name}.json`);
  process.stdout.write(`${repo.name} … `);
  try {
    // `REA_SCAN_REUSE=1` re-renders the document from the JSON already on disk
    // (a full re-run takes minutes and clones every repository again).
    let res = null;
    if (process.env.REA_SCAN_REUSE === '1' && fs.existsSync(raw)) {
      res = JSON.parse(fs.readFileSync(raw, 'utf8'));
    }
    if (!res && !fs.existsSync(path.join(dir, '.git'))) {
      await run('git', ['clone', '--depth', '1', '-q', repo.url, dir], { timeout: 300000 });
    }
    res = res || await call({
      action: 'rea', op: 'run', tool: 'analyze_javascript_application',
      args: { input_path: dir, format: 'directory', detail: 'summary', max_semantic_nodes: 20000 }
    });
    fs.writeFileSync(raw, JSON.stringify(res, null, 2));
    const text = (res.result?.content || []).map((c) => c.text || '').join('');
    const record = JSON.parse(text);
    const coverage = record.normalized_result?.coverage || {};
    rows.push({
      name: repo.name,
      ok: Boolean(res.ok) && !res.result?.isError,
      ms: res.ms,
      evidence: record.evidence_id || null,
      sha256: record.normalized_result?.artifact?.sha256 || null,
      coverage: coverage.status || null,
      examined: coverage.examined ?? null,
      total: coverage.total ?? null,
      unknowns: (record.normalized_result?.unknowns || []).length,
      limitations: (record.normalized_result?.limitations || []).length
    });
    console.log(`${res.ms} ms · ${coverage.examined}/${coverage.total} · ${record.evidence_id}`);
  } catch (e) {
    rows.push({ name: repo.name, ok: false, error: String(e.message || e) });
    console.log(`failed: ${e.message}`);
  }
}

const now = new Date().toISOString().slice(0, 10);
const okRows = rows.filter((r) => r.ok);
const limits = okRows.length
  ? { min: Math.min(...okRows.map((r) => r.limitations)), max: Math.max(...okRows.map((r) => r.limitations)) }
  : { min: 0, max: 0 };
const table = rows.map((r) => (r.ok
  ? `| \`${r.name}\` | ${(r.ms / 1000).toFixed(1)} s | ${r.examined}/${r.total} | ${r.unknowns} | \`${r.evidence}\` |`
  : `| \`${r.name}\` | failed | — | — | ${r.error} |`)).join('\n');

const doc = `# REA evidence — the QoderAI repositories

Generated by \`node scripts/rea-qoder-scan.mjs\` on ${now} against REA 6.7.0
(\`analyze_javascript_application\`, \`format: directory\`, \`detail: summary\`).

An evidence record is what REA returns instead of an opinion: the artifact's
SHA-256, a coverage claim, and the unknowns it refuses to guess at. Coverage is
per view: a repository with documentation only reports \`0 of 1\`, an explicit
"nothing to analyse" rather than a silent success.

| repository | time | examined | unknowns | evidence id |
| --- | --- | --- | --- | --- |
${table || '| — | — | — | — | — |'}

## What this proves, and what it does not

* Each run started from a fresh \`git clone --depth 1\` of the repository and
  analysed the tree, not a memory of it.
* REA reports its own limits per run (${limits.min}–${limits.max} limitation records per
  repository here), and those are kept in \`.rea-scan/<repo>.json\`.
* It does **not** prove that the code was executed. Nothing here runs a
  repository's tests or its binaries; the point of the analysis was to read the
  API contracts this app implements (\`lib/qoder.js\`) out of the code and the
  docs, and to have a record of the exact bytes that were read.

## Repositories that are not in the table

The other ${QODER_REPOS.length - ANALYSABLE.size} repositories are release notes, blog
placeholders, or empty (\`skills\`, \`qoder-community\`, \`qoder-plugins-official\`,
\`qoder-sdk-demos\`, \`cloud-agents-cli\`, \`cloud-agents-sdk-go\`). Cloning them
produces no analysable artifact, which is why \`lib/qoder-repos.js\` labels them
\`changelog\` / \`docs\` / \`empty\` instead of listing them as integrations.
\`qodercli-bench-qwen3.8\` (868 MB of benchmark assets) is linked but not cloned.
`;

fs.writeFileSync(DOC, doc);
console.log(`\nwrote ${path.relative(root, DOC)} (${rows.length} repositories)`);
